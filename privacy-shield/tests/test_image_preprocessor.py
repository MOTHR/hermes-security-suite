"""Tests for the image OCR preprocessor (Phase 2).

Exercises the Tesseract-backed :class:`ImagePreprocessor` end-to-end on a
real PNG generated by ``scripts/generate_test_image.py``.  All tests
bootstrap the fixture on demand so the binary file does not need to be
checked in.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from privacy_shield.preprocessors.image import (
    HEIC_SUPPORTED,
    ImagePreprocessor,
    OCRResult,
    OCRWord,
)

SAMPLE_IMAGE = Path(__file__).parent / "fixtures" / "sample_invoice.png"


def _ensure_fixture() -> None:
    """Generate the sample PNG on-demand if it is missing."""
    if SAMPLE_IMAGE.exists():
        return
    SAMPLE_IMAGE.parent.mkdir(parents=True, exist_ok=True)
    from PIL import Image, ImageDraw, ImageFont

    image = Image.new("RGB", (1200, 900), color="white")
    draw = ImageDraw.Draw(image)

    def _font(size: int) -> ImageFont.ImageFont:
        for candidate in (
            "/System/Library/Fonts/Helvetica.ttc",
            "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        ):
            try:
                return ImageFont.truetype(candidate, size)
            except OSError:
                continue
        return ImageFont.load_default()

    y = 60
    draw.text((50, y), "RECHNUNG / INVOICE", fill="black", font=_font(34))
    y += 70
    for line in (
        "Kunde: Max Mustermann",
        "Email: max.mustermann@example.com",
        "IBAN: DE89370400440532013000",
        "Steuer-ID: 123456789",
        "Telefon: +49 30 12345678",
        "Datum: 21.08.2026",
        "Betrag: 1.234,56 EUR",
    ):
        draw.text((50, y), line, fill="black", font=_font(24))
        y += 44
    image.save(SAMPLE_IMAGE)


@pytest.fixture(scope="module", autouse=True)
def fixture_image() -> None:
    _ensure_fixture()


# ----------------------------------------------------------------- supported_formats


def test_supported_formats_includes_smartphone_defaults():
    pre = ImagePreprocessor()
    fmts = pre.supported_formats
    # Base formats are always available.
    for ext in (".jpg", ".jpeg", ".png", ".webp", ".tiff", ".bmp"):
        assert ext in fmts, f"missing base format {ext}"
    # HEIC is only present when pillow-heif is installed.
    if HEIC_SUPPORTED:
        assert ".heic" in fmts
        assert ".heif" in fmts


def test_is_supported_case_insensitive():
    pre = ImagePreprocessor()
    assert pre.is_supported(Path("photo.JPG"))
    assert pre.is_supported(Path("photo.PNG"))
    assert pre.is_supported(Path("photo.Heic")) == HEIC_SUPPORTED
    assert not pre.is_supported(Path("archive.zip"))


# ----------------------------------------------------------------- extract


def test_extract_returns_ocrresult_with_metadata():
    pre = ImagePreprocessor()
    result = pre.extract(SAMPLE_IMAGE)
    assert isinstance(result, OCRResult)
    assert result.source == SAMPLE_IMAGE
    assert result.lang == "deu+eng"
    assert result.width == 1200
    assert result.height == 900
    assert result.confidence_avg > 0
    assert len(result.words) > 0
    for word in result.words:
        assert isinstance(word, OCRWord)
        assert word.text
        assert word.confidence >= pre.min_confidence
        assert set(word.bbox.keys()) == {"x", "y", "w", "h"}


def test_extract_finds_invoice_text():
    pre = ImagePreprocessor()
    result = pre.extract(SAMPLE_IMAGE)
    # Tesseract may capitalise / mis-spell, so use substring / case-insensitive.
    upper = result.text.upper()
    assert "RECHNUNG" in upper or "INVOICE" in upper
    # Email is the most reliably-OCR'd PII (no German umlauts).
    assert "MAX" in upper
    assert "MUSTERMANN" in upper
    assert "@EXAMPLE.COM" in upper
    # IBAN is high-confidence thanks to the DE prefix.
    assert "DE89" in result.text.replace(" ", "").upper()


def test_extract_drops_low_confidence_words():
    pre = ImagePreprocessor(min_confidence=99)
    result = pre.extract(SAMPLE_IMAGE)
    # With the bar at 99, every word is dropped → empty result.
    assert result.text == ""
    assert result.words == []
    assert result.confidence_avg == 0.0


def test_extract_preserves_line_breaks():
    pre = ImagePreprocessor()
    result = pre.extract(SAMPLE_IMAGE)
    # The sample image is multi-line; the rebuilt text must keep newlines.
    assert "\n" in result.text
    lines = [ln for ln in result.text.split("\n") if ln.strip()]
    assert len(lines) >= 3


def test_extract_missing_file_raises():
    pre = ImagePreprocessor()
    with pytest.raises(FileNotFoundError):
        pre.extract(Path("/nonexistent/photo.png"))


def test_extract_unsupported_format_raises_valueerror(tmp_path: Path):
    fake = tmp_path / "archive.zip"
    fake.write_bytes(b"PK\x03\x04not-an-image")
    pre = ImagePreprocessor()
    with pytest.raises(ValueError, match="Unsupported image format"):
        pre.extract(fake)


def test_extract_malformed_image_raises_valueerror(tmp_path: Path):
    fake = tmp_path / "broken.png"
    fake.write_bytes(b"\x89PNG\r\n\x1a\nnot-a-real-png-body")
    pre = ImagePreprocessor()
    with pytest.raises(ValueError, match="OCR fehlgeschlagen"):
        pre.extract(fake)


def test_extract_overrides_lang():
    pre = ImagePreprocessor()
    result = pre.extract(SAMPLE_IMAGE, lang="eng")
    assert result.lang == "eng"


# ----------------------------------------------------------------- render


def test_render_sanitized_writes_png(tmp_path: Path):
    pre = ImagePreprocessor()
    sanitized_text = (
        "RECHNUNG / INVOICE\n"
        "Kunde: TOKEN_NAME_xxxxxxxxxx_001\n"
        "Email: TOKEN_EMAIL_xxxxxxxxxx_001\n"
        "IBAN: TOKEN_IBAN_xxxxxxxxxx_001"
    )
    output = tmp_path / "sanitized.png"
    written = pre.render_sanitized(SAMPLE_IMAGE, sanitized_text, output)
    assert written == output
    assert output.exists()
    assert output.stat().st_size > 1000
    # Restore dir must be chmod 700 (PII / tokens never leak).
    mode = output.parent.stat().st_mode & 0o777
    assert mode == 0o700, f"expected 0o700, got {oct(mode)}"


def test_render_sanitized_handles_empty_text(tmp_path: Path):
    pre = ImagePreprocessor()
    output = tmp_path / "empty.png"
    pre.render_sanitized(SAMPLE_IMAGE, "", output)
    assert output.exists()


def test_render_sanitized_truncates_long_lines(tmp_path: Path):
    pre = ImagePreprocessor()
    long_text = "x" * 5000
    output = tmp_path / "long.png"
    # Should not raise; the renderer caps at _OVERLAY_LINE_MAX_CHARS per line.
    pre.render_sanitized(SAMPLE_IMAGE, long_text, output)
    assert output.exists()
