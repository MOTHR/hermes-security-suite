"""Tests for the PDF text-preprocessor.

Uses a real PDF generated by ``scripts/generate_test_pdf.py`` so the
extractor exercises the pdfplumber code path end-to-end.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from privacy_shield.preprocessors.pdf import PDFPreprocessor

SAMPLE_PDF = Path(__file__).parent / "fixtures" / "sample_invoice.pdf"


def _ensure_fixture() -> None:
    """Generate the sample PDF on-demand if it is missing.

    Lets the test suite bootstrap itself without committing binary files.
    """
    if SAMPLE_PDF.exists():
        return
    SAMPLE_PDF.parent.mkdir(parents=True, exist_ok=True)
    from reportlab.lib.pagesizes import letter
    from reportlab.pdfgen import canvas

    c = canvas.Canvas(str(SAMPLE_PDF), pagesize=letter)
    c.drawString(50, 750, "RECHNUNG / INVOICE")
    c.drawString(50, 720, "Kunde: Max Mustermann")
    c.drawString(50, 700, "Email: max.mustermann@example.com")
    c.drawString(50, 680, "IBAN: DE89370400440532013000")
    c.drawString(50, 660, "Steuer-ID: 123456789")
    c.drawString(50, 640, "Date: 2026-08-21")
    c.save()


@pytest.fixture(scope="module", autouse=True)
def fixture_pdf() -> None:
    _ensure_fixture()


def test_extract_text():
    pdf = PDFPreprocessor()
    text = pdf.extract(SAMPLE_PDF)
    assert "[PAGE 1]" in text
    assert len(text) > 100
    # The sample invoice contains "RECHNUNG" or "INVOICE" depending on locale.
    assert "RECHNUNG" in text or "INVOICE" in text


def test_extract_pages():
    pdf = PDFPreprocessor()
    pages = pdf.extract_pages(SAMPLE_PDF)
    assert len(pages) >= 1
    for page in pages:
        assert "page" in page
        assert "text" in page
        assert "width" in page
        assert "height" in page


def test_restore_pdf(tmp_path: Path):
    pdf = PDFPreprocessor()
    sanitized_text = (
        "[PAGE 1]\nKontakt: TOKEN_EMAIL_xxxxxx_000\nRechnung: 1234\n"
        "[PAGE 2]\nMehr Inhalt: keine PII."
    )
    output = tmp_path / "sanitized.pdf"
    pdf.restore_pdf(sanitized_text, output)
    assert output.exists()
    assert output.stat().st_size > 100  # reportlab produces real PDFs


def test_extract_chunks():
    """PERF-5: extract_chunks yields page chunks without loading all pages in memory."""
    pdf = PDFPreprocessor()
    chunks = list(pdf.extract_chunks(SAMPLE_PDF, chunk_size=1))
    assert len(chunks) >= 1
    # Each chunk still contains the page marker
    assert all("[PAGE" in chunk for chunk in chunks)
    # With chunk_size=1 on a single-page fixture we get exactly one chunk.
    assert len(chunks) == 1


def test_extract_chunks_chunk_size_zero_uses_one():
    """PERF-5: chunk_size=0 is clamped to 1 to avoid infinite loop."""
    pdf = PDFPreprocessor()
    chunks = list(pdf.extract_chunks(SAMPLE_PDF, chunk_size=0))
    assert len(chunks) == 1


def test_extract_chunks_multiple_pages(tmp_path: Path):
    """PERF-5: a 3-page PDF yields 2 chunks when chunk_size=2."""
    from reportlab.lib.pagesizes import letter
    from reportlab.pdfgen import canvas

    pdf_path = tmp_path / "three_pages.pdf"
    c = canvas.Canvas(str(pdf_path), pagesize=letter)
    for i in range(3):
        c.drawString(50, 750, f"Page {i + 1}")
        c.showPage()
    c.save()

    pdf = PDFPreprocessor()
    chunks = list(pdf.extract_chunks(pdf_path, chunk_size=2))
    assert len(chunks) == 2
    assert "Page 1" in chunks[0]
    assert "Page 2" in chunks[0]
    assert "Page 3" in chunks[1]


def test_extract_chunks_malformed_file_raises_valueerror(tmp_path: Path):
    fake_pdf = tmp_path / "fake.pdf"
    fake_pdf.write_text("not a real pdf")
    pdf = PDFPreprocessor()
    with pytest.raises(ValueError):
        list(pdf.extract_chunks(fake_pdf))


def test_extract_chunks_missing_file_raises():
    pdf = PDFPreprocessor()
    with pytest.raises(FileNotFoundError):
        list(pdf.extract_chunks(Path("/nonexistent/sample.pdf")))


